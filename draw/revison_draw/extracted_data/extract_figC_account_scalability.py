#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Extract Fig. C account/data-size scalability throughput data."""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from pprint import pformat


PROJECT_ROOT = Path(__file__).resolve().parents[4]
DEFAULT_DATA_SIZE_DIR = PROJECT_ROOT / "vldb_res" / "20260731203627（data-size)"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "figC_account_scalability.py"

SYSTEMS = [
    ("RR", "0"),
    ("MWR", "25"),
    ("PHR", "2"),
    ("PAR", "23"),
    ("CPR", "28"),
    ("MP-Router", "11"),
]

ACCOUNT_COUNTS = [
    ("1M", "1000000"),
    ("5M", "5000000"),
    ("10M", "10000000"),
    ("20M", "20000000"),
    ("50M", "50000000"),
    ("100M", "100000000"),
]

SMALLBANK_TEMPLATE = (
    "smallbank_p1_ZipfTheta0.8_ZipfGenfinite_acc{accounts}"
    "_t16_r0.8_b10000_n4_nb1_whpart0_kp1.1_mlp0"
)


def read_after_warmup_tps(result_file: Path) -> float:
    text = result_file.read_text(errors="ignore")
    match = re.search(r"Throughput \(after warmup\):\s*([0-9.]+)", text)
    if not match:
        raise RuntimeError(f"Cannot find after-warmup throughput in {result_file}")
    return round(float(match.group(1)), 2)


def result_path(root: Path, accounts: str, mode: str) -> Path:
    folder = SMALLBANK_TEMPLATE.format(accounts=accounts)
    return root / folder / f"m{mode}" / "result.txt"


def extract_account_scalability(data_size_dir: Path) -> list[tuple[str, list[float | None]]]:
    data = []
    for label, accounts in ACCOUNT_COUNTS:
        values = []
        for _, mode in SYSTEMS:
            path = result_path(data_size_dir, accounts, mode)
            values.append(read_after_warmup_tps(path) if path.exists() else None)
        data.append((label, values))
    return data


def write_module(output: Path, data_size_dir: Path, data: list[tuple[str, list[float | None]]]) -> None:
    system_names = [name for name, _ in SYSTEMS]
    placeholder_labels = [label for label, _ in ACCOUNT_COUNTS]
    lines = [
        "# Auto-generated by extract_figC_account_scalability.py.",
        "# Do not edit by hand; rerun the extractor with the intended data directory.",
        "#",
        f"# Account-scalability source: {data_size_dir}",
        "",
        f"MAIN_SYSTEMS = {pformat(system_names, width=120)}",
        "",
        f"account_scalability_data = {pformat(data, width=120)}",
        "",
        f"ACCOUNT_PLACEHOLDER_LABELS = {pformat(placeholder_labels, width=120)}",
        "",
    ]
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-size-dir", type=Path, default=DEFAULT_DATA_SIZE_DIR)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    data = extract_account_scalability(args.data_size_dir)
    write_module(args.output, args.data_size_dir, data)

    print(f"Wrote {args.output}")
    print(f"Account-scalability source: {args.data_size_dir}")


if __name__ == "__main__":
    main()
