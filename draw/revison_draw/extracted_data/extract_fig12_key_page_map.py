#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Extract Fig. 12 key-page-map capacity data from result.txt files."""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from pprint import pformat


PROJECT_ROOT = Path(__file__).resolve().parents[4]
DEFAULT_MAIN_DIR = PROJECT_ROOT / "vldb_res" / "20260709000616(main)"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "fig12_key_page_map.py"

SYSTEMS = [
    ("PHR", "2"),
    ("PAR", "23"),
    ("CPR", "28"),
    ("MP-Router", "11"),
]

KEY_PAGE_RATIOS = [
    ("20%", "0.2"),
    ("40%", "0.4"),
    ("60%", "0.6"),
    ("80%", "0.8"),
    ("100%", "1.0"),
]

SMALLBANK_TEMPLATE = (
    "smallbank_p1_ZipfTheta0.8_ZipfGenfinite_acc10000000"
    "_t16_r0.8_b10000_nb1_whpart0_kp{ratio}_mlp0"
)


def read_after_warmup_tps(result_file: Path) -> float:
    text = result_file.read_text(errors="ignore")
    match = re.search(r"Throughput \(after warmup\):\s*([0-9.]+)", text)
    if not match:
        raise RuntimeError(f"Cannot find after-warmup throughput in {result_file}")
    return round(float(match.group(1)), 2)


def read_after_warmup_hits(result_file: Path) -> tuple[int, int]:
    """Recover measurement counts from cumulative counters in the saved run.

    The experiment's recorded revision (5aa2a6a) copies hot_hit/hot_miss
    unchanged in diff_snapshot, even when the report is labelled [delta].
    Subtract the warmup-end counters from the final performance snapshot.
    """
    text = result_file.read_text(errors="replace")
    warmup_marker = "Warmup rounds completed. Create the smart router snapshot."
    final_marker = "=== Performance Report ==="
    warmup_pos = text.find(warmup_marker)
    final_pos = text.find(final_marker, warmup_pos)
    if warmup_pos < 0 or final_pos < 0:
        raise RuntimeError(f"Missing snapshot boundaries in {result_file}")
    pattern = r"Hot page hit:\s*(\d+), miss:\s*(\d+)"
    snapshots = []
    for section in (text[warmup_pos:final_pos], text[final_pos:]):
        matches = re.findall(pattern, section)
        if len(matches) != 1:
            raise RuntimeError(f"Expected one counter pair per snapshot in {result_file}")
        snapshots.append(tuple(map(int, matches[0])))
    hits, misses = (snapshots[1][i] - snapshots[0][i] for i in range(2))
    if hits < 0 or misses < 0 or hits + misses == 0:
        raise RuntimeError(f"Invalid measurement counters in {result_file}")
    return hits, misses


def result_path(root: Path, ratio: str, mode: str) -> Path:
    folder = SMALLBANK_TEMPLATE.format(ratio=ratio)
    path = root / folder / f"m{mode}" / "result.txt"
    if not path.exists():
        raise FileNotFoundError(path)
    return path


def extract_key_page_map(main_dir: Path) -> list[tuple[str, list[float]]]:
    data = []
    for label, ratio in KEY_PAGE_RATIOS:
        values = []
        for _, mode in SYSTEMS:
            values.append(read_after_warmup_tps(result_path(main_dir, ratio, mode)))
        data.append((label, values))
    return data


def extract_hit_counts(main_dir: Path) -> dict[str, list[tuple[int, int]]]:
    return {
        name: [read_after_warmup_hits(result_path(main_dir, ratio, mode))
               for _, ratio in KEY_PAGE_RATIOS]
        for name, mode in SYSTEMS
    }


def write_module(output: Path, main_dir: Path, data: list[tuple[str, list[float]]],
                 hit_counts: dict[str, list[tuple[int, int]]]) -> None:
    system_names = [name for name, _ in SYSTEMS]
    hit_rates = {
        name: [100.0 * hits / (hits + misses) for hits, misses in counts]
        for name, counts in hit_counts.items()
    }
    lines = [
        "# Auto-generated by extract_fig12_key_page_map.py.",
        "# Do not edit by hand; rerun the extractor with the intended data directory.",
        "#",
        f"# Key-page-map source: {main_dir}",
        "",
        f"KP_SYSTEMS = {pformat(system_names, width=120)}",
        "",
        f"key_page_map_data = {pformat(data, width=120)}",
        "",
        "# Same capacity order as key_page_map_data; counters exclude warmup.",
        "# Each tuple is (hits, misses); these are map lookups, not page accuracy.",
        f"KP_LOOKUP_COUNTS = {pformat(hit_counts, width=120, sort_dicts=False)}",
        "",
        f"KP_HIT_RATES = {pformat(hit_rates, width=120, sort_dicts=False)}",
        "",
    ]
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--main-dir", type=Path, default=DEFAULT_MAIN_DIR)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    data = extract_key_page_map(args.main_dir)
    hit_counts = extract_hit_counts(args.main_dir)
    write_module(args.output, args.main_dir, data, hit_counts)

    print(f"Wrote {args.output}")
    print(f"Key-page-map source: {args.main_dir}")
    for name, counts in hit_counts.items():
        print(f"{name} hit rates (%): " + ", ".join(
            f"{100.0 * h / (h + m):.2f}" for h, m in counts))


if __name__ == "__main__":
    main()
